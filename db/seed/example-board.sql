-- 자유게시판 **예시 글 다섯** — 운영팀이 적는 안내 글 (지시서 C)
-- ════════════════════════════════════════════════════════════════════
-- ⚠️⚠️ **마이그레이션이 아닙니다.** `db/migrations` 에 두지 않았고
--   `db/apply-from-0008.sql` 에도 안 들어갑니다 — 운영 DB 를 올리는 날
--   같이 올라가면 안 됩니다.
--
-- ⚠️⚠️⚠️ **지시서가 "개발/스테이징 환경에만" 이라고 못박았습니다.**
--   운영 사이트에 넣으셔야 할 일이 생기면 **별도 승인 전에는 넣지
--   않습니다.** 넣으신 뒤에도 —
--     · 제목의 **`[예시]`** 표기를 그대로 둡니다
--     · **실제 이용자 수 · 활동량으로 집계하지 않습니다**
--       (우리 지표 `biz_metrics()` 는 게시판 글을 안 셉니다 — 그래서
--        이 글들이 매각 지표에 섞이지 않습니다)
--
-- ⚠️⚠️ **실제 회원이 쓴 것처럼 꾸미지 않습니다** (지시서 C).
--   · 글쓴이는 **운영자 계정 하나**입니다. 지어낸 사람을 만들지 않습니다.
--   · **조회 수 · 댓글 수를 손으로 넣지 않습니다** — 둘 다 공개 보기가
--     `cqview` · `ca` 를 **세어서** 냅니다 (절대 규칙 1).
--   · 연락처 · 성함을 넣지 않습니다.
--
-- ⚠️ **두 번 돌려도 글이 두 벌 생기지 않습니다** (지시서: idempotent).
--   제목으로 보고 이미 있으면 건너뜁니다.
--
-- ⚠️ psql 의 `\set` 을 **안 씁니다** — Supabase SQL 편집기가 그 명령을
--   모릅니다. 아래 `00000000-0000-0000-0000-000000000000` 을 **찾아
--   바꾸기**로 사장님 계정 uuid 로 바꾸십시오. 안 바꾸면 FK 가
--   거절합니다 (조용히 넘어가지 않습니다).
--   계정 uuid 보는 법:  select id, email from auth.users;
--
-- ⚠️⚠️ 닉네임을 정해 두시면 글쓴이 자리에 그 닉네임이 나옵니다
--   (안 정하셨으면 가린 성함). 0059 의 `set_my_nick` 으로 정하십니다 —
--   ⚠️ **"운영자" · "골프올인원" 같은 이름은 문이 거절합니다**(사칭
--   방지). "골프올인원 운영팀" 으로 두고 싶으시면 그 자물쇠를 먼저
--   보셔야 합니다 — 지금은 거절이 **맞는 동작**입니다.
-- ════════════════════════════════════════════════════════════════════

-- ── ① 넣기 ──────────────────────────────────────────────────────
insert into cq (by_user, cat, title, body)
select '00000000-0000-0000-0000-000000000000'::uuid, v.cat, v.title, v.body
  from (values
    ('cm-open',
     '[예시] 골프올인원 자유게시판 이용 안내',
     '골프에 관한 자유로운 질문과 정보를 나누는 공간입니다. 광고 · 비방 · 개인정보 노출 글은 제한될 수 있습니다.'),
    ('cm-ask',
     '[예시] 처음 골프를 시작할 때 준비할 것은?',
     '골프를 처음 배우는 분들을 위한 자유로운 질문 예시입니다. 레슨, 장갑, 연습장 선택 등에 관해 이야기해 보세요.'),
    ('cm-open',
     '[예시] 중고 골프채 구매 전 확인할 점',
     '샤프트 스펙, 그립 상태, 헤드 손상, 정품 여부 등을 확인해 보세요. 이 글은 게시판 기능 테스트용 예시입니다.'),
    ('cm-open',
     '[예시] 골프 조인 게시글 작성 팁',
     '날짜, 지역, 골프장, 티오프 시간, 모집 인원, 예상 비용을 명확히 적어 주세요. 실제 모집글이 아닙니다.'),
    ('cm-open',
     '[예시] 연습장 선택할 때 무엇을 보시나요?',
     '위치, 가격, 타석 환경, 운영 시간 등을 비교해 보세요. 이 글은 예시 게시글입니다.')
  ) as v(cat, title, body)
 -- ⚠️ 두 번 돌려도 두 벌이 안 생깁니다
 where not exists (select 1 from cq c where c.title = v.title);

