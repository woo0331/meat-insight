window.amTitle = function(pageTitle, route){
  var B = window.AM_BRAND || {};
  var name = B.name || "", sub = B.sub || "";
  if(route === "/") return name + " | " + (pageTitle || "");
  return (pageTitle ? pageTitle + " · " : "") + name + " · " + sub;
};
