window.wowCheckBand = function(score){
  for(var i = 0; i < WOW_CHECK_BANDS.length; i++)
    if(score >= WOW_CHECK_BANDS[i].min) return WOW_CHECK_BANDS[i];
  return WOW_CHECK_BANDS[WOW_CHECK_BANDS.length - 1];
};
