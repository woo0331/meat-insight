/* 이 업종이 어느 대분류인가 */
window.amIndGroupOf = function(indKey){
  var G = window.AM_IND_GROUPS || [];
  for(var i = 0; i < G.length; i++)
    if((G[i].inds || []).indexOf(indKey) >= 0) return G[i];
  return null;
};

/* 대분류마다 **실제로 있는 업종**을 붙여 돌려줍니다.
   ⚠️ 업종이 하나도 없는 대분류는 **줄째 뺍니다** (절대 규칙 2). */
window.amIndGroups = function(){
  var by = {};
  (window.AM_INDUSTRIES || []).forEach(function(i){ by[i.key] = i; });
  return (window.AM_IND_GROUPS || []).map(function(g){
    var inds = (g.inds || []).map(function(k){ return by[k]; }).filter(Boolean);
    return inds.length ? { key:g.key, name:g.name, inds:inds } : null;
  }).filter(Boolean);
};

/* 세부 업종 말 — 검색이 읽는 전부입니다 */
window.amIndSubs = function(indKey){
  return (window.AM_IND_SUBS || {})[indKey] || [];
};

/* ⚠️ 화면에 낼 때는 **몇 개까지만** 냅니다. 스물넷을 다 깔면 업종
   카드가 화면 하나를 통째로 먹습니다 — 짧은 줄은 `lead` 가 맡습니다. */
window.amIndSubsLine = function(indKey, n){
  var s = window.amIndSubs(indKey);
  return s.slice(0, n || 6).join(" · ");
};

