/* ── 찾아 쓰는 함수 ──────────────────────────────────────── */
window.wowPost = function(slug){
  return WOW_POSTS.filter(function(p){ return p.slug === slug; })[0] || null;
};
window.wowPostCat = function(key){
  return WOW_POST_CATS.filter(function(c){ return c.key === key; })[0] || null;
};
window.wowPostCatName = function(key){
  var c = wowPostCat(key);
  /* ⚠️ 못 찾으면 영문 key 를 그대로 찍지 말고 null 을 돌려줍니다 */
  return c ? c.name : null;
};
window.wowPostsIn = function(cat){
  return (!cat || cat === "all") ? WOW_POSTS.slice()
       : WOW_POSTS.filter(function(p){ return p.cat === cat; });
};
/* 같은 분류에서 먼저 고르고, 모자라면 나머지에서 채웁니다 */
window.wowRelated = function(post, n){
  n = n || 3;
  var same = WOW_POSTS.filter(function(p){ return p.slug !== post.slug && p.cat === post.cat; });
  var rest = WOW_POSTS.filter(function(p){ return p.slug !== post.slug && p.cat !== post.cat; });
  return same.concat(rest).slice(0, n);
};
