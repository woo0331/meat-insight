/* 적어 주신 지역을 한 줄로 만듭니다 — "경기 안양" */
window.wowRegionText = function(sido, more){
  var a = String(sido||"").trim(), b = String(more||"").trim();
  return [a, b].filter(Boolean).join(" ");
};
