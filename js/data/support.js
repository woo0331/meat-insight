window.AM_SUPPORTS = [];

window.amSupports = function(side){
  return (window.AM_SUPPORTS||[]).filter(function(s){
    if(!s.link) return false;                 /* 원문 없는 것은 안 냅니다 */
    return !side || s.side === side || s.side === "both";
  });
};
