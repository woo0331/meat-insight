function steps(title, lead, rows){
  return '<section class="sec"><div class="wrap">' +
    '<div class="sec-hd"><h2>' + esc(title) + '</h2><p>' + esc(lead) + '</p></div>' +
    /* ⚠️⚠️ **한 줄에 하나씩** 세웁니다 (`flow-1`). `.flow` 는 2칸
       격자라 걸음이 **다섯**이면 마지막 칸이 빈 자리로 남고(작업 기억의
       "빈 칸이 생기지 않게"), 번호도 1 2 / 3 4 / 5 로 지그재그가 됩니다.
       ⚠️ `.flow` 자체는 안 건드립니다 — `/match` · `/join` 이 같이
       쓰는데 거기는 넷이라 2칸이 맞습니다. */
    '<ol class="flow flow-1">' + rows.map(function(r, i){
      return '<li><span class="flow-n">' + (i+1) + '</span>' +
        '<div><h3>' + esc(r[0]) + '</h3><p>' + esc(r[1]) + '</p></div></li>';
    }).join("") + '</ol></div></section>';
}

