function steps(title, lead, rows){
  return '<section class="sec"><div class="wrap">' +
    '<div class="sec-hd"><h2>' + esc(title) + '</h2><p>' + esc(lead) + '</p></div>' +
    '<ol class="flow">' + rows.map(function(r, i){
      return '<li><span class="flow-n">' + (i+1) + '</span>' +
        '<div><h3>' + esc(r[0]) + '</h3><p>' + esc(r[1]) + '</p></div></li>';
    }).join("") + '</ol></div></section>';
}

