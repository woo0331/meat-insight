/* ════════════════════════════════════════════════════════════════════
   고객센터 — /help

   ⚠️⚠️ **주소가 /notice 가 아니라 /help 입니다.** 공지사항이 아니라
   문의받는 자리라서, 나중에 공지 목록이 생겨도 주소가 안 겹칩니다.

   ⚠️⚠️ **전화 · 이메일은 지어낼 수 없습니다** (전자상거래법 제10조).
   비어 있으면 그 줄이 통째로 빠지고, 대신 지금 실제로 되는 것을
   같이 냅니다 — 막다른 길로 두지 않습니다.

   ⚠️⚠️ **네 갈래를 가릅니다** (4차 지시서 §9 — "FAQ, 문의 접수, 신고,
   개인정보 관련 요청을 구분한다"). 갈래마다 **지금 실제로 되는 길**이
   다릅니다 —
     자주 묻는 것     이 화면에서 바로 읽습니다
     신고 · 분쟁      /my 에서 그 요청 · 업체를 골라 엽니다 (0040 의
                      open_report — 로그인과 대상이 있어야 열립니다)
     개인정보 요청    /my 의 제3자 제공 철회 · 요청 취소 (0039), 방침은 /privacy
     입점 문의        /join
     그 밖의 문의     ⚠️ **받을 자리가 없습니다** — 일반 문의를 담는 표가
                      없고 전화 · 이메일도 비어 있습니다. 지어내지 않고
                      그렇다고 적습니다 (§9 "운영 가능한 실제 연락
                      수단만 안내한다").
   ════════════════════════════════════════════════════════════════════ */
var W = global.window, esc = W.esc, icon = W.icon;

exports.build = function(){
  var ways = [
    ["phone", "전화", W.bizVal("phone"), W.bizVal("hours")],
    ["mail",  "이메일", W.bizVal("email"), null]
  ].filter(function(r){ return r[2]; });

  var body = '<section class="pghd"><div class="wrap">' +
    '<nav class="crumb" aria-label="현재 위치"><a href="/">홈</a>' + icon("arrow",14) +
    '<span aria-current="page">고객센터</span></nav>' +
    '<h1>고객센터</h1>' +
    '<p class="pghd-l">이용 중 막히시는 곳이나 업체와의 문제를 알려 주세요.</p>' +
  '</div></section>';

  if(ways.length){
    body += '<section class="sec"><div class="wrap"><div class="ways">' +
      ways.map(function(r){
        return '<div class="way">' + icon(r[0], 24) +
          '<div><h3>' + esc(r[1]) + '</h3><p>' + esc(r[2]) + '</p>' +
          (r[3] ? '<p class="way-h">' + esc(r[3]) + '</p>' : '') + '</div></div>';
      }).join("") + '</div></div></section>';
  }else{
    /* 운영자에게만 말합니다 — 손님 화면에는 무엇을 설정하라고 안 적습니다 */
    console.warn("  ⚠️ /help — 전화 · 이메일이 비어 있어 연락처를 못 냈습니다 " +
                 "(js/data/site.js 의 phone · email · hours).");
  }

  /* ── 어떤 일로 오셨는지 가릅니다 (§9) ───────────────────────────
     ⚠️ 갈래마다 **지금 실제로 되는 곳**으로 보냅니다. 되는 곳이 없는
     갈래는 단추를 안 냅니다 (눌러도 아무 일이 안 나는 단추를 만들지
     않습니다 · 절대 규칙 5). */
  var LANES = [
    { ic:"flag", t:"업체와 있었던 일을 알리고 싶습니다",
      d:"신고와 분쟁은 어느 요청 · 어느 업체에 대한 것인지 골라야 해서, " +
        "내 정보에서 그 건을 열고 넣으십니다. 운영자가 확인 중 · 처리됨 · 반려로 " +
        "옮기고 그 결과가 같은 자리에 남습니다.",
      go:["/my", "내 정보에서 열기"] },
    { ic:"shield", t:"내 정보를 빼거나 동의를 거두고 싶습니다",
      d:"업체에 연락처를 넘기는 동의는 내 정보에서 거두실 수 있고, 거두시면 " +
        "업체가 보던 길이 전부 끊깁니다. 무엇을 모으고 얼마나 두는지는 " +
        "개인정보처리방침에 적어 두었습니다.",
      go:["/privacy", "개인정보처리방침 보기"] },
    { ic:"store", t:"업체로 입점하고 싶습니다",
      d:"사업자등록 정보와 하시는 일을 등록하시면 됩니다. 입점과 업체 정보 " +
        "등록은 무료이고, 지금 받을 수 있는지는 그 화면이 말해 줍니다.",
      go:["/join", "업체 입점하기"] },
    { ic:"info", t:"처음이라 무엇부터 할지 모르겠습니다",
      d:"손님이 하시는 일 · 업체가 하시는 일 · 알아 두실 것을 한 장에 " +
        "적어 두었습니다.",
      go:["/guide", "이용안내 보기"] }
  ];
  body += '<section class="sec"><div class="wrap">' +
    '<div class="sec-hd"><h2>어떤 일로 오셨나요</h2>' +
    '<p>갈래마다 받는 자리가 다릅니다.</p></div>' +
    /* ⚠️ 빌드가 찍는 기본은 **닫힌 쪽**입니다 — js/helpnow.js 가 로그인이
       설정됐을 때만 바꿉니다 (판단은 js/auth.js 한 곳). */
    /* ⚠️⚠️ 아래 "그 밖의 문의 보내기" 구간과 **같은 말을 하지 않습니다**.
       전에는 두 상자가 나란히 "지금은 못 받습니다" 라고 해서 한 화면에
       같은 안내가 둘이었습니다 (지시서 §2 · §3-1). 여기는 **로그인이
       필요한 쪽**만 말합니다. 열렸는지는 js/helpnow.js 가 바꿉니다
       (판단은 js/auth.js 한 곳). */
    '<div id="helpnow" class="hnow">' +
      '<p><b>신고 · 분쟁과 개인정보 요청은 로그인하신 뒤 내 정보에서 넣으십니다.</b></p>' +
      '<p class="hnow-s">어느 요청 · 어느 업체에 대한 것인지 고르셔야 해서 ' +
      '로그인이 필요합니다. 지금은 로그인을 여는 중입니다.</p>' +
    '</div>' +
    '<ul class="lanes">' + LANES.map(function(L){
      return '<li class="lane"><span class="lane-ic">' + icon(L.ic, 24) + '</span>' +
        '<div class="lane-t"><h3>' + esc(L.t) + '</h3><p>' + esc(L.d) + '</p>' +
        '<a class="btn btn-line btn-sm" href="' + esc(L.go[0]) + '">' +
          esc(L.go[1]) + '</a></div></li>';
    }).join("") + '</ul>' +
  '</div></section>';

  /* ── 그 밖의 문의 보내기 (0045 · 지시서 §11) ────────────────────
     ⚠️⚠️ 빌드가 찍는 기본은 **닫힌 쪽**입니다 — js/inquiry.js 가
     Supabase 설정이 있고 보유 기간(inquiryKeep)이 적혀 있을 때만 양식을
     엽니다 (다 적으신 뒤에 실패하는 일이 없도록 · 절대 규칙 5).
     ⚠️⚠️ 열리면 이 상자가 **통째로 양식으로 바뀝니다**. "받을 자리가
     없습니다" 같은 말을 상자 **밖에** 따로 찍어 두면 양식이 열리는 날
     그 줄이 거짓이 됩니다 — 상태를 말하는 자리는 이 상자 하나입니다. */
  body += '<section class="sec sec-alt"><div class="wrap">' +
    '<div class="sec-hd"><h2>그 밖의 문의 보내기</h2>' +
    '<p>위 네 갈래에 없는 것은 여기에 적어 주세요. 운영자가 확인하고 ' +
    '적어 주신 곳으로 답해 드립니다.</p></div>' +
    '<div id="inqbox" class="none">' +
      '<h2>지금은 문의를 받지 못합니다.</h2>' +
      '<p>받을 자리를 준비하고 있습니다. 다 적으신 뒤에 실패하는 일이 ' +
      '없도록, 준비가 끝나기 전에는 양식을 열지 않습니다. ' +
      '없는 전화번호나 이메일을 적어 두지도 않습니다.</p>' +
    '</div>' +
  '</div></section>';

  /* ⚠️⚠️ **"처음이신가요?" 띠를 뺐습니다** (지시서 §2 — 중복).
     바로 위 네 갈래의 넷째 카드가 **같은 말**을 하고 같은 곳(/guide)으로
     보내고 있었습니다. 한 화면에 같은 단추가 둘이면 한쪽만 고치는 날
     둘이 다른 말을 합니다.
     ⚠️ 머리말 메뉴에서 뺀 이용안내로 가는 길 셋 가운데 하나가 이
     화면입니다 — 길은 **넷째 카드로 그대로 남아 있습니다** (길을 안
     남기고 빼면 지운 것과 같습니다). */

  body += '<section class="sec"><div class="wrap">' +
    '<div class="sec-hd"><h2>자주 묻는 것</h2></div>' +
    '<ul class="notes">' +
      /* ⚠️ "업체와 분쟁이 생겼습니다" 도 위 첫째 카드가 **어디서 넣는지**
         까지 말하고 있어 뺐습니다 (§2). 여기는 갈래로 안 나뉘는 것만. */
      /* ⚠️⚠️ **문장 한가운데에 링크를 박지 않습니다.** 글줄 높이가 19px 라
         손가락으로 못 누릅니다 (전수 점검이 잡았습니다). 문단 끝에
         단추로 뺍니다 — 40px 이상입니다. */
      /* ⚠️ "입점하고 싶습니다" · "내 정보를 넘기나요" 는 위 네 갈래 카드가
         같은 말을 하고 있었습니다 (지시서 §2 — 중복). 여기는 **갈래로
         나뉘지 않는 것**만 둡니다. */
      '<li><b>돈이 드나요?</b> 손님은 요청 · 비교 · 상담까지 무료입니다. ' +
      '업체는 입점과 정보 등록이 무료이고, 연결 · 거래가 성사될 때 수수료가 생깁니다.</li>' +
      '<li><b>요청하면 바로 업체가 붙나요?</b> 아닙니다. 조건에 맞는 업체에 운영자가 ' +
      '전달하고, 업체가 제안을 내면 그것을 비교해 고르십니다. 업체가 없는 분야는 ' +
      '없다고 말씀드립니다 — 지어내지 않습니다.</li>' +
      '<li><b>연락처는 언제 업체에 넘어가나요?</b> 요청하실 때가 아니라, ' +
      '어느 업체인지 정해진 뒤입니다. 그때 상호를 알려 드리고 다시 여쭙습니다.</li>' +
    '</ul></div></section>';

  return {
    route: "/help", title: "고객센터", crumbs: [["고객센터", "/help"]],
    /* ⚠️⚠️ **site.js 를 같이 읽습니다** — 문의 양식이 보여 줄 보유
       기간(inquiryKeep)이 거기 있습니다. 안 실으면 KEEP 이 빈 문자열이
       되어 양식이 **조용히 안 열립니다** (에러도 안 납니다). 실제로
       그렇게 떨어졌습니다 — tools/test-help.js 가 잡았습니다. */
    /* ⚠️⚠️ `site.js`(보유 기간) · `data/deal.js`(문의 갈래) 둘 다
       **실어야** 합니다 — 하나라도 빠지면 `js/inquiry.js` 가 양식을
       조용히 안 엽니다 (설정이 안 된 것과 똑같이 보입니다). */
    js: ["/js/data/site.js", "/js/data/deal.js",
         "/js/helpnow.js", "/js/inquiry.js"],
    desc: "골프올인원 고객센터 — 이용 중 막히는 곳, 업체와의 문제, 입점 문의를 받습니다.",
    body: body
  };
};
