function sec(id, title, lead, items, btns, alt){
  return '<section class="sec' + (alt ? " sec-alt" : "") + '" id="' + id + '">' +
    '<div class="wrap">' +
      '<div class="sec-hd"><h2>' + esc(title) + '</h2></div>' +
      '<p class="mb-lead">' + esc(lead) + '</p>' +
      (items && items.length
        ? '<ul class="mb-li">' + items.map(function(t){
            return '<li>' + esc(t) + '</li>'; }).join("") + '</ul>'
        : "") +
      (btns && btns.length
        ? '<p class="mb-go">' + btns.map(function(b){
            return '<a class="btn btn-sm ' + b[2] + '" href="' + esc(b[0]) + '">' +
                   esc(b[1]) + '</a>'; }).join("") + '</p>'
        : "") +
    '</div>' +
  '</section>';
}

