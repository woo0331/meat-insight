/* ════════════════════════════════════════════════════════════════════
   없는 주소 — 404  (2026-11-05 검수에서 찾았습니다)

   ⚠️⚠️⚠️ **이 화면이 아예 없었습니다.** 저장소에 `404.html` 이 없고
   `vercel.json` 에도 설정이 없어서, 손님이 주소를 잘못 치면 Vercel 의
   기본 404 가 나갔습니다 — 머리말도 · 푸터도 · 중개 고지도 · **돌아갈
   길도 없는** 화면입니다. 막다른 길입니다 (절대 규칙 2).

   ⚠️⚠️ **파일 이름이 `404.html` 이어야 합니다** (`404/index.html` 이
   아닙니다). Vercel 은 정적 사이트에서 **출력 루트의 `404.html`** 을
   없는 주소의 응답으로 씁니다 — 폴더에 넣으면 `/404` 로 직접 들어갈
   때만 보이고 **정작 없는 주소에서는 안 나옵니다.** 그래서 이 화면만
   `build.js` 에서 `file` 을 따로 줍니다.

   ⚠️ **앞 서비스 주소는 여기로 오지 않습니다** — `vercel.json` 이
   167개를 `api/gone.js` 로 보내 **410** 을 냅니다. 404 는 "지금 없다",
   410 은 "있었고 영구히 없앴다" 이고 우리는 그 둘을 압니다. 섞지 마세요.

   ⚠️ `noindex` 입니다 — 사이트맵에 넣지 않습니다 (빌드가 거릅니다).

   ⚠️ **없는 클래스를 지어 쓰지 않았습니다.** `.pghd` · `.none` ·
   `.btn-pt` · `.btn-line` 은 `css/app.css` 에 있는 것입니다 (지어 쓰면
   조용히 아무 모양도 안 입습니다 — `.btn-bad` 로 겪은 자리입니다).
   ════════════════════════════════════════════════════════════════════ */
var W = global.window, icon = W.icon;

exports.build = function(){
  /* ⚠️ 이름 · 주소를 글자로 박지 않습니다 — 분류가 늘거나 이름이 바뀌는
     날 여기만 옛말을 합니다. 가는 곳은 머리말 메뉴와 **같은 넷**입니다. */
  /* ⚠️⚠️ 아이콘 이름은 **글자로** 적습니다 — 없는 이름을 넘기면
     `console.warn` 만 나고 **빈 글자**가 돌아와서, 가로로 밀리지도 ·
     글자가 작지도 않아 어떤 검사도 안 잡습니다. 글자로 적어 두면
     `check-safe` ⑨ 가 셉니다. 처음에 grid · help 로 적었는데
     `js/components/base.js` 에 **둘 다 없는 이름**이었습니다.
     ⚠️ 이 주석에 없는 이름을 **예시로 적지 마세요** — 그 검사는 주석
     안인지 안 가려서, 적어 두면 멀쩡한 파일이 떨어집니다 (실제로
     한 번 떨어뜨렸습니다). */
  var go = [
    ["/categories", "카테고리 전체보기", "menu",   "btn-pt"],
    ["/search",     "업체찾기",          "search", "btn-line"],
    ["/help",       "고객센터",          "chat",   "btn-line"]
  ];

  var body = '<section class="pghd"><div class="wrap">' +
    '<h1>찾으시는 화면이 없습니다</h1>' +
    /* ⚠️ 까닭을 지어내지 않습니다 — 왜 없는지 우리는 모릅니다
       (오타일 수도, 옮긴 주소일 수도 있습니다 · 절대 규칙 5). */
    '<p class="pghd-l">주소가 잘못되었거나, 그 화면이 아직 없습니다. ' +
    '아래에서 가시려던 곳을 골라 주세요.</p>' +
  '</div></section>';

  body += '<section class="sec"><div class="wrap">' +
    '<div class="none">' +
      /* ⚠️ `.none h2` 는 블록이라 **아이콘이 글자에 딱 붙습니다**
         (`.adm-h` 에서 겪은 자리입니다 — 찍어 보고 알았습니다).
         단추마다 이미 아이콘이 있으므로 여기는 글자만 둡니다. */
      '<h2>어디로 가실까요</h2>' +
      '<p>분류를 둘러보시거나, 업체를 바로 찾아보실 수 있습니다. ' +
      '막히시면 고객센터로 알려 주세요.</p>' +
      go.map(function(g){
        return '<a class="btn ' + g[3] + '" href="' + g[0] + '">' +
               icon(g[2], 17) + g[1] + '</a>';
      }).join("") +
    '</div></div></section>';

  return {
    route: "/404",
    /* ⚠️⚠️ 루트의 `404.html` 입니다 — 위 머리말의 까닭을 읽으세요 */
    file: "404.html",
    /* ⚠️ 사이트맵에서 빠지고, 아무 데서도 안 겁니다 (외톨이가 맞습니다) */
    noindex: true,
    unlinked: true,
    title: "찾으시는 화면이 없습니다",
    desc: "골프올인원 — 찾으시는 화면이 없습니다. 카테고리 · 업체찾기 · 고객센터로 가실 수 있습니다.",
    body: body
  };
};
